"""Masks for the BE201 bluetoothd patches, so they follow bluetoothd across Sequoia builds (BlueToolFixup 2.7.13).

Each pattern in BE201Patches.hpp is the exact 24G824 byte sequence. A new build moves functions and data, which changes
the rel32 of direct calls and jumps and the disp32 of RIP-relative operands, and nothing else in these short sequences.
The mask wildcards exactly those bytes, found by disassembling the pattern; opcodes, registers, member offsets,
immediates, short branches and every byte the patch changes stay exact.

Usage: python3 make_masks.py [bluetoothd ...]
Writes BE201PatchMasks.hpp. For each bluetoothd given (fat or thin), checks that every masked pattern matches exactly
once in the x86_64 __TEXT and not across a 4 KiB page, which is what the page hook needs; prints the file offsets."""
import re, struct, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]/'deps/python'))  # capstone 5.0.9
from capstone import Cs, CS_ARCH_X86, CS_MODE_64
from capstone.x86 import X86_OP_MEM, X86_REG_RIP

MASKED = ['Clock', 'LegacyAdv', 'PeerAddress', 'LEBaseline', 'AddressPause']

def patterns():
    hdr = (HERE/'BE201Patches.hpp').read_text()
    return {n: bytes(int(x, 16) for x in body.split(','))
            for n, body in re.findall(r'static const unsigned char kBE201(\w+)\[\] = \{([^}]*)\}', hdr)}

def mask(code):
    md = Cs(CS_ARCH_X86, CS_MODE_64); md.detail = True
    m = bytearray(b'\xff' * len(code)); end = 0
    for i in md.disasm(code, 0):
        end = i.address + i.size
        if i.bytes[0] in (0xe8, 0xe9):
            m[i.address + 1:i.address + 5] = bytes(4)
        for o in i.operands:
            if o.type == X86_OP_MEM and o.mem.base == X86_REG_RIP:
                m[i.address + i.disp_offset:i.address + i.disp_offset + 4] = bytes(4)
    if end < len(code):
        # A pattern may stop inside its last instruction. The only such case is the clock gate's trailing
        # `cmp qword [rip+disp32], imm8` (48 83 3d): keep the opcode, drop the cut displacement.
        tail = code[end:]
        assert tail[:3] == b'\x48\x83\x3d', ('unexpected cut instruction', tail.hex())
        m[end + 3:] = bytes(len(code) - end - 3)
    return bytes(m)

def x86_text(path):
    b = Path(path).read_bytes()
    if struct.unpack_from('<I', b, 0)[0] == 0xbebafeca:
        for i in range(struct.unpack_from('>I', b, 4)[0]):
            cpu, sub, off, size, align = struct.unpack_from('>IIIII', b, 8 + 20 * i)
            if cpu == 0x01000007:
                fat = off; b = b[off:off + size]; break
    else:
        fat = 0
    p = 32
    for _ in range(struct.unpack_from('<I', b, 16)[0]):
        cmd, n = struct.unpack_from('<II', b, p)
        if cmd == 0x19:
            name, vm, vs, fo, fs = struct.unpack_from('<16sQQQQ', b, p + 8)
            if name.rstrip(b'\0') == b'__TEXT':
                return b, fo, fs, fat
        p += n
    raise SystemExit(f'{path}: no x86_64 __TEXT')

def find(hay, pat, m):
    anchor = max(range(len(pat)), key=lambda k: m[k] and k)  # any exact byte
    out, start = [], 0
    while (j := hay.find(pat[anchor:anchor + 1], start)) >= 0:
        s = j - anchor; start = j + 1
        if s >= 0 and s + len(pat) <= len(hay) and all(hay[s + k] == pat[k] for k in range(len(pat)) if m[k]):
            out.append(s)
    return out

def main():
    pats = patterns(); rows = []
    out = ['// Generated by make_masks.py: 0xff = exact byte, 0 = rel32/disp32 that moves between Sequoia builds.',
           '#pragma once']
    for n in MASKED:
        p, q = pats[n + 'Original'], pats[n + 'Patched']; m = mask(p)
        changed = [k for k in range(len(p)) if p[k] != q[k]]
        assert changed and all(m[k] == 0xff for k in changed), (n, 'a patched byte is wildcarded')
        out.append(f'static const unsigned char kBE201{n}Mask[] = {{' + ','.join(f'0x{x:02x}' for x in m) + '};')
        rows.append((n, p, m, changed))
    (HERE/'BE201PatchMasks.hpp').write_text('\n'.join(out) + '\n')
    print('BE201PatchMasks.hpp:', ', '.join(f'{n} {len(p)} bytes, {m.count(0)} wild' for n, p, m, c in rows))
    ok = True
    for path in sys.argv[1:]:
        b, fo, fs, fat = x86_text(path); hay = b[fo:fo + fs]
        for n, p, m, changed in rows:
            hits = find(hay, p, m)
            page_ok = all((fo + h) // 4096 == (fo + h + len(p) - 1) // 4096 for h in hits)
            ok &= len(hits) == 1 and page_ok
            print(f'  {Path(path).name} {n}: {len(hits)} match' + ''.join(f' @0x{fat + fo + h:x}' for h in hits) +
                  ('' if page_ok else ' CROSSES A PAGE'))
    raise SystemExit(0 if ok else 1)

if __name__ == '__main__':
    main()
